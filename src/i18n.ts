export function getMessages(language: Language) {
  return language === "en" ? en : zh;
}

// 异步动作保存错误码，呈现时按当前语言翻译，不把旧语言错误缓存进界面。
export class SidebarError extends Error {
  constructor(readonly code: keyof typeof zh.errors) {
    super(zh.errors[code]);
    this.name = "SidebarError";
  }
}

export function describeError(error: unknown, language: Language): string {
  if (error instanceof SidebarError) return getMessages(language).errors[error.code];
  if (error instanceof Error) return error.message;
  return String(error);
}
